@pytest.mark.parametrize("source,expected", CASES)
def test_scrub_table(source, expected):
    assert scrub(source) == expected


def test_every_rule_is_exercised_by_the_cases():
    unused = [name for name, pattern, _ in RULES if not any(pattern.search(source) for source, _ in CASES)]
    # path-rest and hub-of-direction are fallbacks for forms not seen in the base at the moment.
    assert set(unused) <= {"path-rest", "hub-of-direction"}, unused


def test_scrub_is_idempotent_on_the_cases():
    for _, expected in CASES:
        assert scrub(expected) == expected


def test_scrub_leaves_legal_text_and_names_alone():
    text = (
        "ПП № 1119 пп. 5, 9–11; ст. 6 ч. 1 152-ФЗ; Хабаровское УФАС; публикация на Хабре; "
        "Wikimedia Commons; B2P и P2P сервисы; Приложение 1 к приказу № 5"
    )
    assert scrub(text) == text


def test_scrub_keeps_raw_word():
    assert "raw" in scrub("в raw P22 нет, см. raw")
